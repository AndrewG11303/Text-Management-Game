def main():
    """Main entry point"""
    args = parse_arguments()
    
    # Handle setup wizard
    if args.setup:
        run_setup_wizard()
        return 0
    
    # Handle screenshot
    if args.screenshot:
        take_screenshot()
        return 0
    
    # Print banner
    print_banner()
    
    # Check if config exists
    config_path = Path(args.config)
    if not config_path.exists():
        print(f"⚠️  Config file not found: {config_path}")
        print("   Run 'python main.py --setup' to create one")
        print("   Or the bot will use default settings\n")
    
    # Import bot engine (after path setup)
    from src.bot_engine import BotEngine
    
    # Create bot instance
    try:
        bot = BotEngine(args.config)
    except Exception as e:
        print(f"❌ Failed to initialize bot: {e}")
        return 1
    
    # Handle debug mode
    if args.debug:
        bot.logger.logger.setLevel('DEBUG')
        bot.logger.info("Debug mode enabled")
    
    # Handle single task
    if args.task:
        print(f"\n🎯 Running single task: {args.task}\n")
        success = bot.run_single_task(args.task)
        return 0 if success else 1
    
    # Handle status check
    if args.status:
        status = bot.get_status()
        print("\n📊 Bot Status:")
        for key, value in status.items():
            print(f"   {key}: {value}")
        return 0
    
    # Run bot
    try:
        print("\n🚀 Starting bot...\n")
        print("   Press Ctrl+C to stop\n")
        bot.start(duration_hours=args.hours)
        return 0
    except KeyboardInterrupt:
        print("\n\n⚠️  Interrupted by user")
        bot.stop()
        return 0
    except Exception as e:
        print(f"\n❌ Error: {e}")
        bot.stop()
        return 1


if __name__ == '__main__':
    sys.exit(main())
